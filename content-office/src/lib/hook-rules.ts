// 후킹은 구체적인 정보 약속. 과장·공포·근거 없는 수치는 제외.
export const HOOK_RULES = `후킹 문구는 과장 없이 구체적이어야 합니다.
- 원문에서 확인되는 대상·문제·얻는 정보를 표지에 명확히 드러내세요. 원문이 없으면 주제 범위를 설명하고 효과·결과는 약속하지 마세요.
- 근거 없는 숫자·기간·가격·절약률, 효과 보장(무조건·100%·완벽·실패 없는), 공포(망한다·큰일), 낚시(모르면 손해·저장 안 하면 후회·충격·비밀) 금지.
- 후보 3개는 문제 해결형 / 판단 기준형 / 구체적인 방법 안내형으로 각도를 달리하세요. 원문의 사실·수치만 사용하고 뒷받침되지 않으면 표현을 낮추세요.
- 참고 사례의 문구·성과를 복사하지 마세요. 출력 직전 각 후킹의 주장과 숫자가 원문에 있는지 스스로 점검하세요.`;
export function groundedHook(value: string, source: string) {
  if (/무조건|100\s*%|완벽|실패\s*없|망해|망하|큰일|모르면\s*손해|안\s*하면\s*후회|충격|기적|보장|절대|다\s*터져|2배|두\s*배/.test(value)) return false;
  const numbers: string[] = source.match(/\d+(?:[.,]\d+)*/g) ?? [];
  return (value.match(/\d+(?:[.,]\d+)*/g) ?? []).every(n=>numbers.includes(n));
}
